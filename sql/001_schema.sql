-- SmartCity Analytics: esquema relacional PostgreSQL (17 tablas)
-- Ejecutar con psql sobre smartcity_db. Es idempotente para facilitar reinicios.

BEGIN;

CREATE TABLE IF NOT EXISTS categorias_sensor (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria TEXT NOT NULL UNIQUE CHECK (trim(nombre_categoria) <> '')
);

CREATE TABLE IF NOT EXISTS tipos_sensor (
    id_tipo_sensor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tipo TEXT NOT NULL UNIQUE CHECK (trim(nombre_tipo) <> ''),
    id_categoria BIGINT NOT NULL REFERENCES categorias_sensor(id_categoria)
);

CREATE TABLE IF NOT EXISTS ciudades (
    id_ciudad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    pais TEXT NOT NULL CHECK (trim(pais) <> ''),
    zona_horaria TEXT,
    UNIQUE (pais, nombre)
);

CREATE TABLE IF NOT EXISTS ubicaciones (
    id_ubicacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ciudad BIGINT NOT NULL REFERENCES ciudades(id_ciudad),
    codigo_zona TEXT NOT NULL CHECK (trim(codigo_zona) <> ''),
    nombre_zona TEXT NOT NULL CHECK (trim(nombre_zona) <> ''),
    distrito TEXT,
    latitud NUMERIC(9,6) CHECK (latitud BETWEEN -90 AND 90),
    longitud NUMERIC(9,6) CHECK (longitud BETWEEN -180 AND 180),
    CHECK ((latitud IS NULL) = (longitud IS NULL)),
    UNIQUE (id_ciudad, codigo_zona)
);

CREATE TABLE IF NOT EXISTS organismos_responsables (
    id_organismo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    responsable TEXT
);

CREATE TABLE IF NOT EXISTS usuarios_sistema (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    correo TEXT NOT NULL UNIQUE CHECK (trim(correo) <> '')
);

CREATE TABLE IF NOT EXISTS sensores (
    id_sensor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_sensor TEXT NOT NULL UNIQUE CHECK (trim(codigo_sensor) <> ''),
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    id_tipo_sensor BIGINT NOT NULL REFERENCES tipos_sensor(id_tipo_sensor),
    id_ubicacion BIGINT NOT NULL REFERENCES ubicaciones(id_ubicacion),
    id_organismo BIGINT REFERENCES organismos_responsables(id_organismo),
    fecha_instalacion DATE,
    estado_administrativo TEXT NOT NULL CHECK (estado_administrativo IN ('activo', 'inactivo')),
    naturaleza_sensor TEXT NOT NULL CHECK (naturaleza_sensor IN ('fisico', 'logico'))
);

CREATE TABLE IF NOT EXISTS fuentes_datos (
    id_fuente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    version TEXT NOT NULL CHECK (trim(version) <> ''),
    url_origen TEXT,
    licencia TEXT,
    naturaleza_datos TEXT NOT NULL CHECK (naturaleza_datos IN ('real', 'sintetica', 'no_verificada')),
    UNIQUE (nombre, version)
);

CREATE TABLE IF NOT EXISTS variables_medicion (
    id_variable BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_variable TEXT NOT NULL UNIQUE CHECK (trim(codigo_variable) <> ''),
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    definicion TEXT,
    unidad TEXT NOT NULL CHECK (trim(unidad) <> ''),
    criterio_agregacion TEXT
);

CREATE TABLE IF NOT EXISTS tipos_sensor_variables (
    id_tipo_sensor BIGINT NOT NULL REFERENCES tipos_sensor(id_tipo_sensor),
    id_variable BIGINT NOT NULL REFERENCES variables_medicion(id_variable),
    PRIMARY KEY (id_tipo_sensor, id_variable)
);

CREATE TABLE IF NOT EXISTS lecturas_limpias (
    id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sensor BIGINT NOT NULL REFERENCES sensores(id_sensor),
    id_fuente BIGINT NOT NULL REFERENCES fuentes_datos(id_fuente),
    clave_origen TEXT NOT NULL CHECK (trim(clave_origen) <> ''),
    id_documento_mongo TEXT UNIQUE,
    fecha_medicion TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_recepcion TIMESTAMP WITH TIME ZONE NOT NULL,
    calidad TEXT NOT NULL CHECK (calidad IN ('valida', 'parcial', 'sin_valores_validos')),
    clase_lectura TEXT NOT NULL CHECK (clase_lectura IN ('parking', 'trafico', 'otra')),
    intervalo_segundos INTEGER CHECK (intervalo_segundos > 0),
    UNIQUE (id_fuente, clave_origen)
);

CREATE TABLE IF NOT EXISTS mediciones_limpias (
    id_lectura BIGINT NOT NULL REFERENCES lecturas_limpias(id_lectura) ON DELETE CASCADE,
    id_variable BIGINT NOT NULL REFERENCES variables_medicion(id_variable),
    valor NUMERIC NOT NULL CHECK (valor > '-Infinity'::numeric AND valor < 'Infinity'::numeric),
    PRIMARY KEY (id_lectura, id_variable)
);

CREATE TABLE IF NOT EXISTS estacionamientos (
    id_estacionamiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente BIGINT NOT NULL REFERENCES fuentes_datos(id_fuente),
    id_ubicacion BIGINT NOT NULL REFERENCES ubicaciones(id_ubicacion),
    codigo_origen TEXT NOT NULL CHECK (trim(codigo_origen) <> ''),
    nombre TEXT,
    UNIQUE (id_fuente, codigo_origen)
);

CREATE TABLE IF NOT EXISTS rutas (
    id_ruta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_fuente BIGINT NOT NULL REFERENCES fuentes_datos(id_fuente),
    id_ciudad BIGINT NOT NULL REFERENCES ciudades(id_ciudad),
    codigo_origen TEXT NOT NULL CHECK (trim(codigo_origen) <> ''),
    nombre TEXT,
    UNIQUE (id_fuente, id_ciudad, codigo_origen)
);

CREATE TABLE IF NOT EXISTS niveles_congestion (
    id_nivel BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE CHECK (trim(codigo) <> ''),
    nombre TEXT NOT NULL CHECK (trim(nombre) <> ''),
    orden SMALLINT NOT NULL UNIQUE CHECK (orden >= 0)
);

CREATE TABLE IF NOT EXISTS lecturas_parking (
    id_lectura BIGINT PRIMARY KEY REFERENCES lecturas_limpias(id_lectura) ON DELETE CASCADE,
    id_estacionamiento BIGINT NOT NULL REFERENCES estacionamientos(id_estacionamiento)
);

CREATE TABLE IF NOT EXISTS lecturas_trafico (
    id_lectura BIGINT PRIMARY KEY REFERENCES lecturas_limpias(id_lectura) ON DELETE CASCADE,
    id_ruta BIGINT REFERENCES rutas(id_ruta),
    id_nivel BIGINT REFERENCES niveles_congestion(id_nivel)
);

CREATE OR REPLACE VIEW vw_ultima_lectura_sensor AS
SELECT s.id_sensor, s.codigo_sensor, u.nombre_zona,
       max(l.fecha_medicion) AS ultima_lectura,
       count(l.id_lectura) AS cantidad_lecturas
FROM sensores s
JOIN ubicaciones u ON u.id_ubicacion = s.id_ubicacion
LEFT JOIN lecturas_limpias l ON l.id_sensor = s.id_sensor
GROUP BY s.id_sensor, s.codigo_sensor, u.nombre_zona;

CREATE OR REPLACE FUNCTION fn_sensores_por_tipo(p_id_tipo_sensor BIGINT)
RETURNS TABLE (id_sensor BIGINT, codigo_sensor TEXT, nombre TEXT, estado_administrativo TEXT)
LANGUAGE SQL AS $$
    SELECT s.id_sensor, s.codigo_sensor, s.nombre, s.estado_administrativo
    FROM sensores s WHERE s.id_tipo_sensor = p_id_tipo_sensor
    ORDER BY s.id_sensor
$$;

CREATE OR REPLACE PROCEDURE pr_cambiar_estado_sensor(p_id_sensor BIGINT, p_nuevo_estado TEXT)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_nuevo_estado NOT IN ('activo', 'inactivo') THEN
        RAISE EXCEPTION 'Estado no valido: %', p_nuevo_estado;
    END IF;
    UPDATE sensores SET estado_administrativo = p_nuevo_estado WHERE id_sensor = p_id_sensor;
END;
$$;

CREATE INDEX IF NOT EXISTS ix_sensores_tipo ON sensores(id_tipo_sensor);
CREATE INDEX IF NOT EXISTS ix_sensores_ubicacion ON sensores(id_ubicacion);
CREATE INDEX IF NOT EXISTS ix_sensores_organismo ON sensores(id_organismo);
CREATE INDEX IF NOT EXISTS ix_lecturas_sensor_fecha ON lecturas_limpias(id_sensor, fecha_medicion DESC);
CREATE INDEX IF NOT EXISTS ix_lecturas_fecha ON lecturas_limpias(fecha_medicion);
CREATE INDEX IF NOT EXISTS ix_lecturas_fuente_fecha ON lecturas_limpias(id_fuente, fecha_medicion);
CREATE INDEX IF NOT EXISTS ix_mediciones_variable ON mediciones_limpias(id_variable, id_lectura);
CREATE INDEX IF NOT EXISTS ix_estacionamientos_ubicacion ON estacionamientos(id_ubicacion);
CREATE INDEX IF NOT EXISTS ix_rutas_ciudad ON rutas(id_ciudad);
CREATE INDEX IF NOT EXISTS ix_lecturas_trafico_ruta ON lecturas_trafico(id_ruta);

COMMIT;
